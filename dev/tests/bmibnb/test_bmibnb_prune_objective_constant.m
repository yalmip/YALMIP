tests = functiontests(localfunctions);

function test_negative_objective_constant(testCase)
sdpvar x y
F = [0 <= x <= 1, 0 <= y <= 1, x+y == 1];
objective = -10 - x*y + 0.6*x;
options = sdpsettings('solver','bmibnb', ...
    'bmibnb.uppersolver','none', ...
    'bmibnb.diagonalize',0, ...
    'bmibnb.lpreduce',0, ...
    'bmibnb.roottight',0, ...
    'bmibnb.maxiter',100, ...
    'bmibnb.relgaptol',1e-6, ...
    'bmibnb.absgaptol',1e-6, ...
    'verbose',0);

solution = optimize(F,objective,options);

testCase.verifyEqual(solution.problem,0);
testCase.verifyLessThan(abs(value(objective)+10.04),1e-5);
