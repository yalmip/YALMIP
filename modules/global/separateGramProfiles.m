function [rows,info] = separateGramProfiles(p,x)
% Root separator for exact class-size profiles in binary Gram blocks.
% All cheap gates run before the quadratic Gram-pattern scan.
timer = tic;
nvars = numel(p.c);
rows = sparse(0,nvars+1);
info = struct('reason','model gate','generatedRows',0,'addedRows',0, ...
    'maxViolation',0,'seconds',0,'records',[],'detectorEntered',false);
if ~isfield(p,'K') || ~isfield(p.K,'s') || numel(p.K.s) ~= 1 || ...
        ~isfield(p.K,'f') || ~isfield(p.K,'l') || ...
        ~all(isfield(p.K,{'q','r','e','p','c','m','sos','rank'})) || ...
        ~isstruct(p.K.sos) || ~isfield(p.K.sos,'type') || ...
        ~isfield(p,'F_struc') || ~isfield(p,'isbinary') || ...
        ~isfield(p,'binary_variables') || ...
        ~isfield(p,'integral_variables') || ...
        ~isfield(p,'lb') || ~isfield(p,'ub') || ...
        ~all(isfield(p,{'f','Q','evalMap','variabletype', ...
            'nonlinear','semicont_variables'}))
    info.seconds = toc(timer);
    return
end
n = p.K.s(1);
npairs = n*(n-1)/2;
if n < 24 || n > 40 || p.K.f ~= 0 || p.K.l < 2*n || ...
        nvars ~= npairs || numel(x) ~= nvars || ...
        size(p.F_struc,2) ~= nvars+1 || ...
        nnz(p.F_struc) > 2e5 || size(p.F_struc,1) > 5e4 || ...
        numel(p.isbinary) < nvars || ~all(p.isbinary(1:nvars)) || ...
        ~isequal(sort(p.binary_variables(:)),(1:nvars)') || ...
        ~isequal(sort(p.integral_variables(:)),(1:nvars)') || ...
        numel(p.lb) < nvars || numel(p.ub) < nvars || ...
        any(p.lb(1:nvars) ~= 0) || any(p.ub(1:nvars) ~= 1) || ...
        ~isfield(p,'options') || ~isfield(p.options,'bnb') || ...
        ~isfield(p.options.bnb,'cuts') || ~p.options.bnb.cuts
    info.seconds = toc(timer);
    return
end
if any(p.K.q) || any(p.K.r) || ...
        any(p.K.e) || any(p.K.p) || ...
        any(p.K.c) || ~isequal(p.K.m,0) || ...
        ~isempty(p.K.sos.type) || ...
        (~isempty(p.K.rank) && any(p.K.rank(:) < n)) || ...
        nnz(p.Q) || ~isempty(p.evalMap) || ...
        any(p.variabletype) || ~isempty(p.nonlinear) || ...
        ~isempty(p.semicont_variables)
    info.seconds = toc(timer);
    return
end
% A partition model needs a lower and upper incident-star row for nearly
% every vertex. Counting supports is cheaper than examining SDP entries.
starSupports = sum(spones(p.F_struc(1:p.K.l,2:end)),2);
if nnz(starSupports == n-1) < 2*n
    info.reason = 'no star rows';
    info.seconds = toc(timer);
    return
end
if ~isreal(p.F_struc) || ~isreal(x) || ...
        any(~isfinite(nonzeros(p.F_struc))) || ...
        any(~isfinite(p.c)) || ~isfinite(p.f) || ...
        any(~isfinite(x(:)))
    info.reason = 'nonfinite data';
    info.seconds = toc(timer);
    return
end
info.detectorEntered = true;
gram = initGramTriangleSeparator(p,24);
if numel(gram) ~= 1
    info.reason = 'Gram detector';
    info.seconds = toc(timer);
    return
end
pairVariables = nonzeros(triu(gram{1}.pair,1));
if numel(pairVariables) ~= npairs || ...
        numel(unique(pairVariables)) ~= npairs || ...
        ~isequal(sort(pairVariables), (1:nvars)')
    info.reason = 'pair map';
    info.seconds = toc(timer);
    return
end
[candidate,records] = deriveGramProfileCuts(p,gram);
info.records = records;
info.generatedRows = size(candidate,1);
if isempty(candidate)
    info.reason = 'no stronger profile rows';
    info.seconds = toc(timer);
    return
end
residual = full(candidate*[1;x(:)]);
info.maxViolation = max(0,-min(residual));
rows = candidate(residual < -1e-5,:);
info.addedRows = size(rows,1);
if info.addedRows > 0
    info.reason = 'violated profile rows';
else
    info.reason = 'profile rows satisfied';
end
info.seconds = toc(timer);
end
